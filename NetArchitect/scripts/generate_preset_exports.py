import json
import csv
from pathlib import Path
from core.input_validator import validate_scenario
from core.scenario_manager import load_preset
from core.project_engine import analyze_scenario

ROOT = Path(__file__).resolve().parents[1]
for profile in ("campus_lan", "metro_man", "global_wan"):
    scenario = validate_scenario(load_preset(profile))
    result = analyze_scenario(scenario)
    out = ROOT / "exports" / profile
    out.mkdir(parents=True, exist_ok=True)
    for filename, content in result["configurations"].items():
        (out / filename).write_text(content, encoding="utf-8")
    (out / "decision_report.json").write_text(
        json.dumps(result["decision_report"], indent=2), encoding="utf-8"
    )
    (out / "vlsm_allocations.json").write_text(
        json.dumps([s.__dict__ for s in result["subnets"]], indent=2), encoding="utf-8"
    )
    with (out / "vlsm_allocations.csv").open("w", newline="", encoding="utf-8") as handle:
        rows = [s.__dict__ for s in result["subnets"]]
        writer = csv.DictWriter(handle, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
    (out / "SIMULATION_REQUIRED.txt").write_text(
        "These files were generated by NetArchitect. They have NOT yet been loaded "
        "or verified in Packet Tracer/GNS3. Verify against your target Cisco device "
        "models, IOS versions, interface inventory, routing-area/peer details and "
        "security policy before deployment.\n", encoding="utf-8"
    )
    print(f"Generated {profile} exports: {out}")
